// Disposable PostgreSQL integration test. Pass the installed PGlite module path
// as argv[2], or install @electric-sql/pglite outside the application runtime.
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
const { PGlite } = await import(process.argv[2] ? pathToFileURL(process.argv[2]).href : '@electric-sql/pglite');
const db = new PGlite();
await db.exec(`create role authenticated; create schema auth; create table auth.users(id uuid primary key);
create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
grant usage on schema auth to authenticated; grant execute on function auth.uid() to authenticated;`);
for (const name of ['202609050001_initial_schema.sql','202609050002_fix_hosted_invite_codes.sql','202609060001_shared_chore_workflows.sql']) {
  const sql = await readFile(new URL(`../supabase/migrations/${name}`, import.meta.url), 'utf8');
  await db.exec(sql.replace('create extension if not exists pgcrypto;', ''));
}
const owner = '00000000-0000-4000-8000-000000000001';
const guest = '00000000-0000-4000-8000-000000000002';
const outsider = '00000000-0000-4000-8000-000000000003';
await db.exec(`insert into auth.users values ('${owner}'),('${guest}'),('${outsider}');`);
const as = async (user) => { await db.exec(`reset role; set request.jwt.claim.sub='${user}'; set role authenticated;`); };
const rpc = async (name, args) => (await db.query(`select public.${name}(${args.map((_, i) => `$${i+1}`).join(',')}) as value`, args)).rows[0].value;
await as(owner);
const created = await rpc('create_household', ['Chore test house','Jamie','#F36F56']);
const hid = created.household.id;
await as(guest);
const joined = await rpc('join_household', [created.household.invite_code,'Sam','#9ED9C5']);
const board = () => rpc('get_chore_board', [hid]);
const date = new Date(); date.setUTCDate(date.getUTCDate()+1);
const input = { title: 'Clean kitchen', points: 3, assigneeIds: [created.member.id, joined.member.id], dueAt: date.toISOString(), dueInDays: 1, repeatEvery: 1, repeatUnit: 'weeks', recurrence: 'every 1 week', starterTitle: null };
await as(outsider);
await assert.rejects(board, /membership/);
assert.equal((await db.query('select * from public.member_point_totals')).rows.length,0);
await assert.rejects(() => rpc('request_chore_change',[hid,'create',input]), /membership/);
await as(owner);
await assert.rejects(() => db.exec(`update public.chores set points=1`), /permission/);
await assert.rejects(() => rpc('write_chore',[hid,input,null,null]), /permission/);
const pending = await rpc('request_chore_change',[hid,'create',input]);
assert.equal(pending.status,'pending'); assert.equal((await board()).chores.length,0);
await as(guest);
await rpc('vote_chore_change',[hid,pending.pending.id,'approved']);
let c = (await board()).chores[0];
assert.equal(c.assigneeIds.length,2);
await as(owner);
const edit = await rpc('request_chore_change',[hid,'edit',{ ...input, title:'Kitchen reset', points:5,choreId:c.id,scope:'occurrence',expectedVersion:1 }]);
assert.equal((await board()).chores[0].points,3);
await as(guest);
await rpc('vote_chore_change',[hid,edit.pending.id,'approved']);
c = (await board()).chores[0]; assert.equal(c.points,5);
await assert.rejects(() => rpc('request_chore_change',[hid,'edit',{ ...input,choreId:c.id,scope:'future',expectedVersion:1 }]), /changed/);
const completed = await rpc('complete_chore',[c.id,'first']);
await as(owner);
const retried = await rpc('complete_chore',[c.id,'second-device']);
assert.equal(completed.id,retried.id);
let totals = (await db.query('select * from public.member_point_totals')).rows;
assert.equal(Number(totals.find((m) => m.member_id===joined.member.id).total_points),5);
assert.equal(Number(totals.find((m) => m.member_id===created.member.id).total_points),0);
// Advance the prior due date as an administrator instead of waiting a week.
await db.exec('reset role');
await db.query(`update public.chores set due_at=now()-interval '8 days',scheduled_at=now()-interval '8 days' where id=$1`,[c.id]);
await as(owner);
const next = (await board()).chores.find((item) => item.id!==c.id);
assert.equal(next.title,'Clean kitchen'); assert.equal(next.points,3);
assert.equal((await board()).chores.length,2);
const deletion = await rpc('request_chore_change',[hid,'archive',{ choreId:next.id,scope:'future',expectedVersion:1 }]);
await as(guest); await rpc('vote_chore_change',[hid,deletion.pending.id,'approved']);
assert.ok((await board()).chores.find((item) => item.id===next.id).archivedAt);
await assert.rejects(() => rpc('complete_chore',[next.id,'deleted']), /deleted/);
assert.equal((await board()).completions.length,1);
assert.equal((await board()).chores.length,2);
totals = (await db.query('select * from public.member_point_totals')).rows;
assert.equal(Number(totals.find((m) => m.member_id===joined.member.id).total_points),5);
// Open trust still requires every roommate to approve relaxing the policy.
const trust = await rpc('request_chore_change',[hid,'trust',{nextTrustLevel:'open'}]);
assert.equal((await board()).trustLevel,'everything-except-date');
await as(owner); await rpc('vote_chore_change',[hid,trust.pending.id,'approved']);
assert.equal((await board()).trustLevel,'open');
await assert.rejects(() => rpc('request_chore_change',[hid,'create',{...input,assigneeIds:[outsider]}]), /Assignee/);
const direct = await rpc('request_chore_change',[hid,'create',{...input,title:'One-time tidy',repeatEvery:null,repeatUnit:null,dueAt:'',recurrence:'one time'}]);
assert.equal(direct.status,'created');
await rpc('request_chore_change',[hid,'archive',{choreId:direct.chore.id,expectedVersion:1,scope:'occurrence'}]);
assert.ok((await board()).chores.find((item)=>item.id===direct.chore.id).archivedAt);
console.log('Database checks passed: migrations, two-user approvals, RLS, create/edit/archive, recurrence, stale edits, completion retries, and saved member totals.');
await db.close();
